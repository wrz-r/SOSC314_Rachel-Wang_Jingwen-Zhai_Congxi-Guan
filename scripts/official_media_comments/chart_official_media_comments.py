# Pie Chart:
# Topic Distribution of Pilot Comments, 2025
# ==========================================

import pandas as pd
import matplotlib.pyplot as plt

# ------------------------------------------
# 1. Load the dataset
# ------------------------------------------

df = pd.read_csv("official_media_comments_2025.csv")


# ------------------------------------------
# 2. Fill parent-post information
# ------------------------------------------
# Some rows only contain comment-level information.
# This step fills the parent-post metadata for all comments
# belonging to the same parent post.

parent_columns = [
    "official_account",
    "post_created_at",
    "post_month",
    "keyword_group",
    "keyword_categories",
    "matched_keywords",
    "parent_post_text"
]

for col in parent_columns:
    df[col] = (
        df.groupby("parent_post_id")[col]
          .transform(lambda x: x.ffill().bfill())
    )


# ------------------------------------------
# 3. Rename topic groups
# ------------------------------------------

topic_names = {
    "fertility": "Fertility",
    "marriage": "Marriage",
    "both": "Marriage & Fertility"
}

df["topic"] = df["keyword_group"].replace(topic_names)


# ------------------------------------------
# 4. Set topic order
# ------------------------------------------

topic_order = [
    "Fertility",
    "Marriage & Fertility",
    "Marriage"
]


# ------------------------------------------
# 5. Count comments by topic
# ------------------------------------------

topic_counts = (
    df["topic"]
    .value_counts()
    .reindex(topic_order)
    .fillna(0)
    .astype(int)
)

print("Number of comments by topic:")
print(topic_counts)

print("\nTotal number of comments:")
print(topic_counts.sum())


# ------------------------------------------
# 6. Function to show percentage + count
# ------------------------------------------

def autopct_with_count(values):
    total = values.sum()

    def format_pct(pct):
        count = int(round(pct * total / 100.0))
        if count == 0:
            return ""
        return f"{pct:.1f}%\n(n={count})"

    return format_pct


# ------------------------------------------
# 7. Choose nicer colors
# ------------------------------------------
# Soft, report-friendly colors

colors = [
    "#7FB3D5",  # soft blue
    "#F5B7B1",  # soft pink
    "#A9DFBF"   # soft green
]


# ------------------------------------------
# 8. Optional: slightly separate slices
# ------------------------------------------

explode = [0.03, 0.03, 0.06]


# ------------------------------------------
# 9. Create pie chart
# ------------------------------------------

fig, ax = plt.subplots(figsize=(8, 6.5))

wedges, texts, autotexts = ax.pie(
    topic_counts.values,
    labels=topic_counts.index,
    colors=colors,
    explode=explode,
    autopct=autopct_with_count(topic_counts.values),
    startangle=90,
    counterclock=False,
    wedgeprops={
        "edgecolor": "white",
        "linewidth": 2
    },
    textprops={
        "fontsize": 10
    }
)


# ------------------------------------------
# 10. Improve text appearance
# ------------------------------------------

for text in texts:
    text.set_fontsize(11)

for autotext in autotexts:
    autotext.set_fontsize(10)
    autotext.set_color("black")


# ------------------------------------------
# 11. Add title
# ------------------------------------------

ax.set_title(
    "Topic Distribution of Pilot Comments, 2025",
    fontsize=15,
    pad=18
)


# ------------------------------------------
# 12. Keep the chart circular
# ------------------------------------------

ax.set_aspect("equal")


# ------------------------------------------
# 13. Adjust layout
# ------------------------------------------

plt.tight_layout()


# ------------------------------------------
# 14. Save figure
# ------------------------------------------

plt.savefig(
    "pilot_comments_topic_pie_pretty.png",
    dpi=300,
    bbox_inches="tight"
)


# ------------------------------------------
# 15. Show figure
# ------------------------------------------

plt.show()


